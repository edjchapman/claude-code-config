"""Tests for the Claude-attribution guard: the line matcher and the pull-request CLI."""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPT = REPO_ROOT / "scripts" / "check-attribution.py"

sys.path.insert(0, str(REPO_ROOT / "scripts"))
from lib.attribution import find_attribution  # noqa: E402

ADDRESS = "<noreply@anthropic.com>"
TRAILER = f"Co-Authored-By: Claude {ADDRESS}"
GENERATED = "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"
SESSION = "Claude-Session: https://claude.ai/code/session_0123"


class LineMatcher(unittest.TestCase):
    def assert_flagged(self, line: str) -> None:
        self.assertEqual(find_attribution(f"fix: a thing\n\n{line}\n"), [(3, line)])

    def assert_clean(self, text: str) -> None:
        self.assertEqual(find_attribution(text), [])

    def test_co_author_trailer_is_matched_on_the_address_not_the_name(self) -> None:
        for name in ("Claude", "Claude Opus 4.5", "Claude Opus 4.8 (1M context)", "Anything"):
            with self.subTest(name=name):
                self.assert_flagged(f"Co-Authored-By: {name} {ADDRESS}")

    def test_trailer_key_is_case_insensitive(self) -> None:
        for key in ("Co-Authored-By", "Co-authored-by", "co-authored-by", "CO-AUTHORED-BY"):
            with self.subTest(key=key):
                self.assert_flagged(f"{key}: Claude {ADDRESS}")

    def test_generated_with_line_with_or_without_emoji_and_link(self) -> None:
        for line in (
            GENERATED,
            "Generated with [Claude Code](https://claude.com/claude-code)",
            "🤖 Generated with Claude Code",
            "Generated with Claude Code",
        ):
            with self.subTest(line=line):
                self.assert_flagged(line)

    def test_generated_by_footer_with_or_without_emphasis_and_link(self) -> None:
        for line in (
            FOOTER,
            "Generated by [Claude Code](https://claude.ai/code)",
            "_Generated by Claude Code_",
            "Generated by Claude Code",
            "*Generated by [Claude Code](https://claude.ai/code)*",
            "*Generated by Claude Code*",
            "_Generated with [Claude Code](https://claude.com/claude-code)_",
        ):
            with self.subTest(line=line):
                self.assert_flagged(line)

    def test_footer_after_a_rule_is_reported_with_its_line_number(self) -> None:
        text = f"## Summary\n\nDid a thing.\n\n---\n{FOOTER}\n"
        self.assertEqual(find_attribution(text), [(6, FOOTER)])

    def test_session_trailer(self) -> None:
        self.assert_flagged(SESSION)
        self.assert_flagged("claude-session: https://claude.ai/code/session_0123")

    def test_trailing_whitespace_does_not_hide_a_line(self) -> None:
        self.assertEqual(find_attribution(f"{TRAILER}  \r\n"), [(1, TRAILER)])

    def test_every_hit_is_reported_with_its_line_number(self) -> None:
        text = f"feat: a thing\n\nbody\n\n{GENERATED}\n\n{TRAILER}\n"
        self.assertEqual(find_attribution(text), [(5, GENERATED), (7, TRAILER)])

    def test_human_co_author_passes(self) -> None:
        self.assert_clean("fix: a thing\n\nCo-Authored-By: Ada Lovelace <ada@example.invalid>\n")

    def test_prose_and_inline_code_mentions_pass(self) -> None:
        for text in (
            f"This guard fails on a {TRAILER} trailer.",
            f"- `{TRAILER}`",
            f"`{TRAILER}`",
            f"The trailer `Co-Authored-By: Claude {ADDRESS}` is matched on its address.",
            'It also matches the "Generated with Claude Code" line.',
            "`Generated with Claude Code`",
            "Generated with Claude Code, then edited by hand.",
            f"> {GENERATED}",
            f"`{FOOTER}`",
            f"- `{FOOTER}`",
            f"The routine ends each body with `{FOOTER}` after a rule.",
            'It also matches the "Generated by Claude Code" footer.',
            "Generated by Claude Code, then edited by hand.",
            "* Generated by Claude Code and reviewed by a human",
            f"> {FOOTER}",
            "`sessionUrl: false` suppresses the `Claude-Session:` trailer.",
            "Claude-Session:",
            "noreply@anthropic.com is the stable part.",
        ):
            with self.subTest(text=text):
                self.assert_clean(text)


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        [
            "git",
            "-c",
            "user.name=fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "-c",
            "commit.gpgsign=false",
            "-c",
            "core.hooksPath=/dev/null",
            *args,
        ],
        cwd=repo,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


class PullRequestCli(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.repo = Path(tmp.name) / "repo"
        self.repo.mkdir()
        self.event = Path(tmp.name) / "event.json"
        git(self.repo, "init", "-q", "-b", "main")
        # Already on main, trailer and all: history is not this check's concern.
        self.base = self.commit(f"chore: old work\n\n{TRAILER}")

    def commit(self, message: str) -> str:
        git(self.repo, "commit", "-q", "--allow-empty", "-m", message)
        return git(self.repo, "rev-parse", "HEAD")

    def run_check(self, body: str | None) -> subprocess.CompletedProcess:
        head = git(self.repo, "rev-parse", "HEAD")
        self.event.write_text(
            json.dumps(
                {"pull_request": {"body": body, "base": {"sha": self.base}, "head": {"sha": head}}}
            )
        )
        return subprocess.run(
            [sys.executable, str(SCRIPT), "--event", str(self.event)],
            cwd=self.repo,
            capture_output=True,
            text=True,
        )

    def test_clean_commits_and_body_pass_and_main_is_not_scanned(self) -> None:
        self.commit("feat: new work\n\nCo-Authored-By: Ada Lovelace <ada@example.invalid>")
        self.commit("fix: more work")
        result = self.run_check("## Summary\n\nMentions the `Co-Authored-By` trailer in prose.")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("2 commits", result.stdout)

    def test_commit_with_the_trailer_fails_naming_the_commit(self) -> None:
        self.commit("feat: clean work")
        bad = self.commit(f"fix: trailered work\n\nDetails.\n\n{TRAILER}")
        result = self.run_check("A clean body.")
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn(bad[:12], result.stdout)
        self.assertIn("fix: trailered work", result.stdout)
        self.assertIn(TRAILER, result.stdout)
        self.assertNotIn(self.base[:12], result.stdout)
        self.assertNotIn("PR body", result.stdout)

    def test_body_with_the_generated_line_fails_naming_the_body(self) -> None:
        self.commit("feat: clean work")
        result = self.run_check(f"## Summary\n\nDid a thing.\n\n{GENERATED}\n")
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("PR body, line 5", result.stdout)
        self.assertIn(GENERATED, result.stdout)

    def test_body_ending_with_the_routine_footer_fails_naming_the_body(self) -> None:
        self.commit("feat: clean work")
        result = self.run_check(f"## Summary\n\nDid a thing.\n\n---\n{FOOTER}\n")
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("PR body, line 6", result.stdout)
        self.assertIn(FOOTER, result.stdout)

    def test_an_empty_body_arrives_as_null_and_passes(self) -> None:
        self.commit("feat: clean work")
        result = self.run_check(None)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_a_payload_that_is_not_a_pull_request_is_an_error_not_a_pass(self) -> None:
        self.event.write_text(json.dumps({"push": {}}))
        result = subprocess.run(
            [sys.executable, str(SCRIPT), "--event", str(self.event)],
            cwd=self.repo,
            capture_output=True,
            text=True,
        )
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)


if __name__ == "__main__":
    unittest.main()
